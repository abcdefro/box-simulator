def roll(table):
    """표에서 가중치대로 하나를 뽑는다. 안쪽에 표가 또 있으면 끝까지 내려간다."""
    node = random.choices([n for _, n in table], weights=[w for w, _ in table])[0]
    return roll(node) if isinstance(node, list) else node


def open_all(start_boxes, owned_tanks=(), verbose=True):
    owned = set(owned_tanks)                 # 이미 보유한 전차
    inv = {1: start_boxes, 2: 0, 3: 0}       # 아직 안 열린 상자
    opened = {1: 0, 2: 0, 3: 0}              # 연 상자
    found = {1: 0, 2: 0, 3: 0}               # 상자 안에서 새로 나온 상자
    rewards = Counter()
    new_tanks = []
    dup_tanks = []                           # 중복이라 상위 상자로 바뀐 전차

    # 안 열린 상자가 하나라도 남아 있으면 계속 연다.
    # 상위/하위 상자가 중간에 나와도 inv에 쌓이므로 전부 처리된다.
    while any(inv.values()):
        level = next(l for l in (1, 2, 3) if inv[l] > 0)
        inv[level] -= 1
        opened[level] += 1
        box = BOXES[level]

        # 1) 전차 칸
        prob, tank_table = box["tank"]
        if random.random() < prob:
            tank = roll(tank_table)
            if tank in owned:
                up = min(level + 1, 3)       # 중복 → 상위 상자 (3단계는 3단계 상자)
                inv[up] += 1
                found[up] += 1
                dup_tanks.append((tank, up))
            else:
                owned.add(tank)
                new_tanks.append(tank)

        # 2) 보상 칸들
        for prob, table in box["slots"]:
            if random.random() < prob:
                name, amount = roll(table)
                if name == "BOX":
                    inv[amount] += 1
                    found[amount] += 1
                else:
                    rewards[name] += amount

    if verbose:
        total = sum(opened.values())
        print(f"처음 가진 1단계 상자: {start_boxes:,}개")
        print(f"연 상자 총 {total:,}개  "
              f"(1단계 {opened[1]:,} / 2단계 {opened[2]:,} / 3단계 {opened[3]:,})")
        print(f"상자 안에서 새로 나온 상자: 1단계 {found[1]:,} / 2단계 {found[2]:,} / 3단계 {found[3]:,}")
        print("\n[획득 전차]")
        print("  " + (", ".join(new_tanks) if new_tanks else "없음"))
        if dup_tanks:
            print("  (중복 전차 → 상위 상자로 대체: "
                  + ", ".join(f"{t}→{u}단계 상자" for t, u in dup_tanks) + ")")
        print("\n[획득 보상]")
        for name in sorted(rewards):
            print(f"  {name}: {rewards[name]:,}")
    return opened, found, rewards, new_tanks, dup_tanks


